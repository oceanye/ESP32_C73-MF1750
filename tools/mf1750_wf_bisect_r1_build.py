#!/usr/bin/env python3
"""Generate bisection R1: commented records with the active header.

R20[0:7] remains active (including PLL=0x02); R20[7:535] is exactly the
commented record region.  PWR and PLL follow the active header; R21 and the
runtime sequence are unchanged in the dedicated driver TU.
No device, network, relay or camera access.
"""
from pathlib import Path
import hashlib
import json
import sys

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from host.runtime_waveform import l535_table_builder as builder  # noqa: E402

OUT = ROOT / "src/generated/spd1657_wf_bisect_r1.inc"
REPORT = ROOT / ".test-output/offline/WF_BISECT_R1_20261018_V1/generation-report.json"


def _sha256(payload: bytes) -> str:
    return hashlib.sha256(payload).hexdigest()


def _fmt_array(name: str, payload: bytes) -> str:
    lines = [f"static constexpr std::uint8_t {name}[{len(payload)}] = {{"]
    for i in range(0, len(payload), 16):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in payload[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main() -> None:
    active = builder.from_reference("active").to_bytes()
    commented = builder.from_reference("commented").to_bytes()
    variant = active[:7] + commented[7:]
    builder.validate_table_bytes(variant)
    if variant[:7] != active[:7]:
        raise SystemExit("R1 header is not active")
    if variant[7:] != commented[7:]:
        raise SystemExit("R1 records are not commented")

    header = variant[:7]
    pwr = bytes([0x0F]) + header[0:5]
    pll = bytes([0x02])
    if variant[1:5] != pwr[2:6]:
        raise SystemExit("R20[1:5] != PWR[2:6]")
    if variant[6] != pll[0]:
        raise SystemExit("R20[6] != PLL[0] == 0x02")
    diff = [i for i in range(535) if variant[i] != active[i]]
    if len(diff) != 385 or any(i < 7 for i in diff):
        raise SystemExit(f"R1 diff is not the expected 385 record bytes: {diff}")

    report = {
        "schema_version": 1,
        "kind": "mf1750-wf-bisect-r1-generation",
        "variant_id": "BISECT_R1_RECORDS_COMMENTED_HEADER_ACTIVE",
        "header": list(header),
        "active_r20_sha256": _sha256(active),
        "commented_r20_sha256": _sha256(commented),
        "r20_sha256": _sha256(variant),
        "pwr_sha256": _sha256(pwr),
        "pll_sha256": _sha256(pll),
        "pll_payload": list(pll),
        "pwr_payload": list(pwr),
        "diff_offsets": diff,
        "diff_byte_count_vs_active": len(diff),
        "r21": "active 704 x 0xFF, unchanged in driver",
        "assertions": {
            "header_exactly_active": True,
            "records_exactly_commented": True,
            "diff_only_expected_record_region": True,
            "r20_1_5_eq_pwr_2_6": True,
            "r20_6_eq_pll_0_eq_0x02": True
        }
    }
    out = [
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "// Generated by tools/mf1750_wf_bisect_r1_build.py.  R20[0:7] is active;",
        "// R20[7:535] is the complete commented record region.  PWR and PLL=0x02",
        "// follow the active header.  R21 and the runtime sequence stay unchanged.",
        "",
        "namespace mf1750::runtime_lut::wf_bisect_r1 {",
        "",
        f"// sha256(R20)={report['r20_sha256']}",
        f"// sha256(PWR)={report['pwr_sha256']}; sha256(PLL)={report['pll_sha256']}",
        "static constexpr std::uint8_t kPowerPayload[6] = {",
        "    " + ", ".join(f"0x{b:02X}" for b in pwr) + ",\n};",
        "static constexpr std::uint8_t kPllPayload[1] = {\n    0x02,\n};",
        _fmt_array("kR20Payload", variant),
        "}  // namespace mf1750::runtime_lut::wf_bisect_r1",
        ""
    ]
    content = "\n".join(out)
    if OUT.exists() and OUT.read_text(encoding="utf-8") != content:
        raise SystemExit("bisect-r1 include exists with different content")
    OUT.write_text(content, encoding="utf-8")
    report["include_content_lf_sha256"] = _sha256(content.encode())
    REPORT.write_text(json.dumps(report, indent=1, sort_keys=True), encoding="utf-8")
    print(json.dumps({"r20": report["r20_sha256"], "pwr": report["pwr_sha256"],
                      "pll": report["pll_sha256"], "diff_vs_active": len(diff)}, indent=1))


if __name__ == "__main__":
    main()
