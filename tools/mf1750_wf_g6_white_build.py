#!/usr/bin/env python3
"""Generate the WF White group 6 single-record L535 variant.

Only active R20 bytes [249:260] (zero-based White record/group 6, the
vendor's White-GROUP7) are replaced by the commented table's bytes at the
same position.  Every other R20 byte, PWR, PLL and R21 remains active.

Output: src/generated/spd1657_wf_g6_white.inc (O_EXCL content check).
No device, network, relay or camera access.
"""
from pathlib import Path
import hashlib
import json
import sys

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from host.runtime_waveform import l535_table_builder as builder  # noqa: E402

OUT = ROOT / "src/generated/spd1657_wf_g6_white.inc"
REPORT = ROOT / ".test-output/offline/WF_G6_WHITE_20261017_V1/generation-report.json"
START, END = 249, 260


def _sha256(payload: bytes) -> str:
    return hashlib.sha256(payload).hexdigest()


def _fmt_array(name: str, payload: bytes) -> str:
    lines = [f"static constexpr std::uint8_t {name}[{len(payload)}] = {{"]
    for i in range(0, len(payload), 16):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in payload[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main() -> None:
    active = builder.from_reference("active").to_bytes()
    commented = builder.from_reference("commented").to_bytes()
    if len(active) != 535 or len(commented) != 535:
        raise SystemExit("unexpected L535 geometry")
    if active[START:END] != bytes([0xFF] * 11):
        raise SystemExit("active White group 6 is not the expected all-FF record")
    if commented[START:END] == active[START:END]:
        raise SystemExit("commented White group 6 has no replacement content")

    variant = active[:START] + commented[START:END] + active[END:]
    builder.validate_table_bytes(variant)
    diff = [i for i in range(535) if variant[i] != active[i]]
    if any(i < START or i >= END for i in diff):
        raise SystemExit(f"variant changed bytes outside White group 6: {diff}")
    if len(variant[START:END]) != 11:
        raise SystemExit("White group 6 replacement is not exactly one 11-byte record")
    if variant[260:271] != active[260:271] or variant[260:271] != bytes([0xFF] * 11):
        raise SystemExit("White group 7 changed")

    header = variant[:7]
    pwr = bytes([0x0F]) + header[0:5]
    pll = bytes([0x02])
    if variant[1:5] != pwr[2:6]:
        raise SystemExit("R20[1:5] != PWR[2:6]")
    if variant[6] != pll[0]:
        raise SystemExit("R20[6] != PLL[0] / A1 PLL drifted into G6")
    active_pwr = bytes([0x0F]) + active[:5]
    if pwr != active_pwr:
        raise SystemExit("PWR changed from active")

    report = {
        "schema_version": 1,
        "kind": "mf1750-wf-g6-white-generation",
        "variant_id": "G6_WHITE_RECORD_V1",
        "group_indexing": "zero-based White group 6 [249:260] == vendor White-GROUP7",
        "active_target": list(active[START:END]),
        "commented_source": list(commented[START:END]),
        "replacement_span": [START, END],
        "replacement_bytes": 11,
        "value_diff_offsets": diff,
        "value_diff_byte_count": len(diff),
        "value_identical_offsets_within_replacement": [i for i in range(START, END) if i not in diff],
        "active_r20_sha256": _sha256(active),
        "r20_sha256": _sha256(variant),
        "pwr_sha256": _sha256(pwr),
        "pll_sha256": _sha256(pll),
        "pll_payload": list(pll),
        "pwr_payload": list(pwr),
        "r21": "active 704 x 0xFF, unchanged in driver",
        "assertions": {
            "replacement_is_exactly_one_11b_record_at_249_259": True,
            "all_value_differences_confined_to_replacement_span": True,
            "group_7_unchanged_all_ff": True,
            "r20_1_5_eq_pwr_2_6": True,
            "r20_6_eq_pll_0_eq_0x02": True,
            "pwr_identical_to_active": True
        }
    }
    out = [
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "// Generated by tools/mf1750_wf_g6_white_build.py.  Only R20[249:260]",
        "// (zero-based White group 6 / vendor White-GROUP7) comes from commented;",
        "// every other byte, PWR and PLL=0x02 remain the sealed active baseline.",
        "",
        "namespace mf1750::runtime_lut::wf_g6_white {",
        "",
        f"// sha256(R20)={report['r20_sha256']}",
        f"// sha256(PWR)={report['pwr_sha256']}; sha256(PLL)={report['pll_sha256']}",
        "static constexpr std::uint8_t kPowerPayload[6] = {",
        "    " + ", ".join(f"0x{b:02X}" for b in pwr) + ",\n};",
        "static constexpr std::uint8_t kPllPayload[1] = {\n    0x02,\n};",
        _fmt_array("kR20Payload", variant),
        "}  // namespace mf1750::runtime_lut::wf_g6_white",
        ""
    ]
    content = "\n".join(out)
    if OUT.exists() and OUT.read_text(encoding="utf-8") != content:
        raise SystemExit("g6 include exists with different content - investigate first")
    OUT.write_text(content, encoding="utf-8")
    report["include_content_lf_sha256"] = _sha256(content.encode())
    REPORT.write_text(json.dumps(report, indent=1, sort_keys=True), encoding="utf-8")
    print(json.dumps({"r20": report["r20_sha256"], "pwr": report["pwr_sha256"],
                      "pll": report["pll_sha256"], "diff": diff}, indent=1))


if __name__ == "__main__":
    main()
