#!/usr/bin/env python3
"""Generate the WF full-commented L535 runtime-table variant.

The complete 535-byte R20 payload is the sealed commented table, including its
header and PLL=0x03.  PWR is regenerated from the commented header mirror;
PLL follows the commented header.  R21 and the runtime sequence are unchanged
in the dedicated driver TU.  No device, network, relay or camera access.
"""
from pathlib import Path
import hashlib
import json
import sys

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from host.runtime_waveform import l535_table_builder as builder  # noqa: E402

OUT = ROOT / "src/generated/spd1657_wf_commented_full.inc"
REPORT = ROOT / ".test-output/offline/WF_COMMENTED_FULL_20261018_V1/generation-report.json"


def _sha256(payload: bytes) -> str:
    return hashlib.sha256(payload).hexdigest()


def _fmt_array(name: str, payload: bytes) -> str:
    lines = [f"static constexpr std::uint8_t {name}[{len(payload)}] = {{"]
    for i in range(0, len(payload), 16):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in payload[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main() -> None:
    active = builder.from_reference("active").to_bytes()
    commented = builder.from_reference("commented").to_bytes()
    if len(commented) != 535:
        raise SystemExit("commented table is not the unique 535-byte L535 table")
    variant = bytes(commented)
    builder.validate_table_bytes(variant)
    if variant != commented:
        raise SystemExit("variant differs from commented source")

    header = variant[:7]
    pwr = bytes([0x0F]) + header[0:5]
    pll = bytes([header[6]])
    if pll != bytes([0x03]):
        raise SystemExit("commented PLL identity changed unexpectedly")
    if variant[1:5] != pwr[2:6]:
        raise SystemExit("R20[1:5] != PWR[2:6]")
    if variant[6] != pll[0]:
        raise SystemExit("R20[6] != PLL[0]")
    diff = [i for i in range(535) if variant[i] != active[i]]
    if len(diff) != 389:
        raise SystemExit(f"active/commented identity changed: {len(diff)} differences")

    report = {
        "schema_version": 1,
        "kind": "mf1750-wf-commented-full-generation",
        "variant_id": "COMMENTED_FULL_TABLE_V1",
        "source": "sealed legacy_reference::commented, exactly one namespace",
        "active_r20_sha256": _sha256(active),
        "r20_sha256": _sha256(variant),
        "pwr_sha256": _sha256(pwr),
        "pll_sha256": _sha256(pll),
        "pll_payload": list(pll),
        "pwr_payload": list(pwr),
        "header": list(header),
        "diff_byte_count_vs_active": len(diff),
        "r21": "active 704 x 0xFF, unchanged in driver",
        "assertions": {
            "r20_exactly_equals_commented": True,
            "r20_1_5_eq_pwr_2_6": True,
            "r20_6_eq_pll_0_eq_0x03": True,
            "active_commented_diff_still_389_bytes": True
        }
    }
    out = [
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "// Generated by tools/mf1750_wf_commented_full_build.py.  The complete",
        "// 535-byte R20 table, its header, PWR mirror and PLL=0x03 are the sealed",
        "// commented identity.  R21 and the runtime sequence stay on the active path.",
        "",
        "namespace mf1750::runtime_lut::wf_commented_full {",
        "",
        f"// sha256(R20)={report['r20_sha256']}",
        f"// sha256(PWR)={report['pwr_sha256']}; sha256(PLL)={report['pll_sha256']}",
        "static constexpr std::uint8_t kPowerPayload[6] = {",
        "    " + ", ".join(f"0x{b:02X}" for b in pwr) + ",\n};",
        "static constexpr std::uint8_t kPllPayload[1] = {\n    0x03,\n};",
        _fmt_array("kR20Payload", variant),
        "}  // namespace mf1750::runtime_lut::wf_commented_full",
        ""
    ]
    content = "\n".join(out)
    if OUT.exists() and OUT.read_text(encoding="utf-8") != content:
        raise SystemExit("commented-full include exists with different content")
    OUT.write_text(content, encoding="utf-8")
    report["include_content_lf_sha256"] = _sha256(content.encode())
    REPORT.write_text(json.dumps(report, indent=1, sort_keys=True), encoding="utf-8")
    print(json.dumps({"r20": report["r20_sha256"], "pwr": report["pwr_sha256"],
                      "pll": report["pll_sha256"], "diff_vs_active": len(diff)}, indent=1))


if __name__ == "__main__":
    main()
