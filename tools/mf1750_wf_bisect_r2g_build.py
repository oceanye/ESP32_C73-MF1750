#!/usr/bin/env python3
"""Generate bisection R2G: only White records 4+5 come from commented.

Only White records 4+5 R20[227:249] come from commented.  White records 6+7
and every other byte remain active.  PWR and PLL=0x02 follow the active
header; R21 and the runtime sequence are unchanged in the dedicated driver TU.
No device, network, relay or camera access.
"""
from pathlib import Path
import hashlib
import json
import sys

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from host.runtime_waveform import l535_table_builder as builder  # noqa: E402

OUT = ROOT / "src/generated/spd1657_wf_bisect_r2g.inc"
REPORT = ROOT / ".test-output/offline/WF_BISECT_R2G_20261018_V1/generation-report.json"


def _sha256(payload: bytes) -> str:
    return hashlib.sha256(payload).hexdigest()


def _fmt_array(name: str, payload: bytes) -> str:
    lines = [f"static constexpr std::uint8_t {name}[{len(payload)}] = {{"]
    for i in range(0, len(payload), 16):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in payload[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main() -> None:
    active = builder.from_reference("active").to_bytes()
    commented = builder.from_reference("commented").to_bytes()
    variant = active[:227] + commented[227:249] + active[249:]
    builder.validate_table_bytes(variant)
    if variant[:227] != active[:227] or variant[249:] != active[249:]:
        raise SystemExit("R2G active header or records 0-3/6-7 drifted")
    if variant[227:249] != commented[227:249]:
        raise SystemExit("R2G White records 4+5 are not commented")

    header = variant[:7]
    pwr = bytes([0x0F]) + header[0:5]
    pll = bytes([0x02])
    if variant[1:5] != pwr[2:6]:
        raise SystemExit("R20[1:5] != PWR[2:6]")
    if variant[6] != pll[0]:
        raise SystemExit("R20[6] != PLL[0] == 0x02")
    diff = [i for i in range(535) if variant[i] != active[i]]
    if len(diff) != 18 or any(not 227 <= i < 249 for i in diff):
        raise SystemExit(f"R2G diff is not the expected 18 White records 4+5 bytes: {diff}")

    report = {
        "schema_version": 1,
        "kind": "mf1750-wf-bisect-r2g-generation",
        "variant_id": "BISECT_R2G_WHITE_RECORDS_4_5_COMMENTED",
        "category_boundaries": {"White_records_4_5": [227, 249], "White_records_6_7": [249, 271]},
        "header": list(header),
        "active_r20_sha256": _sha256(active),
        "commented_r20_sha256": _sha256(commented),
        "r20_sha256": _sha256(variant),
        "pwr_sha256": _sha256(pwr),
        "pll_sha256": _sha256(pll),
        "pll_payload": list(pll),
        "pwr_payload": list(pwr),
        "diff_offsets": diff,
        "diff_byte_count_vs_active": len(diff),
        "r21": "active 704 x 0xFF, unchanged in driver",
        "assertions": {
            "header_and_records_0_3_and_6_7_and_all_other_bytes_exactly_active": True,
            "white_records_4_5_exactly_commented": True,
            "diff_only_white_records_4_5": True,
            "r20_1_5_eq_pwr_2_6": True,
            "r20_6_eq_pll_0_eq_0x02": True
        }
    }
    out = [
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "// Generated by tools/mf1750_wf_bisect_r2g_build.py.  Active header and",
        "// every other byte; only White records 4+5 [227:249] are commented.",
        "// PWR/PLL=0x02 follow the active header.  R21/runtime stay unchanged.",
        "",
        "namespace mf1750::runtime_lut::wf_bisect_r2g {",
        "",
        f"// sha256(R20)={report['r20_sha256']}",
        f"// sha256(PWR)={report['pwr_sha256']}; sha256(PLL)={report['pll_sha256']}",
        "static constexpr std::uint8_t kPowerPayload[6] = {",
        "    " + ", ".join(f"0x{b:02X}" for b in pwr) + ",\n};",
        "static constexpr std::uint8_t kPllPayload[1] = {\n    0x02,\n};",
        _fmt_array("kR20Payload", variant),
        "}  // namespace mf1750::runtime_lut::wf_bisect_r2g",
        ""
    ]
    content = "\n".join(out)
    if OUT.exists() and OUT.read_text(encoding="utf-8") != content:
        raise SystemExit("bisect-r2g include exists with different content")
    OUT.write_text(content, encoding="utf-8")
    report["include_content_lf_sha256"] = _sha256(content.encode())
    REPORT.write_text(json.dumps(report, indent=1, sort_keys=True), encoding="utf-8")
    print(json.dumps({"r20": report["r20_sha256"], "pwr": report["pwr_sha256"],
                      "pll": report["pll_sha256"], "diff_vs_active": len(diff)}, indent=1))


if __name__ == "__main__":
    main()
