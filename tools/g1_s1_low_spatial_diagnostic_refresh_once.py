def run_low_spatial_diagnostic_refresh_once(
    diagnostic_dir: Path,
    result_dir: Path,
    base_url: str,
    *,
    confirm_map_prior_unchanged: bool = False,
    confirm_j2_powered_supervised: bool = False,
    confirm_cold_start: bool = False,
    confirm_single_post_authorized: bool = False,
    job_timeout_s: float = DEFAULT_JOB_TIMEOUT_S,
    poll_interval_s: float = DEFAULT_POLL_INTERVAL_S,
    sleeper: Callable[[float], None] = time.sleep,
    clock: Callable[[], float] = time.monotonic,
) -> dict[str, Any]:
    """Consume and run the sole frozen low-spatial diagnostic authorization."""

    if not isinstance(diagnostic_dir, Path) or not isinstance(result_dir, Path):
        raise LowSpatialDiagnosticRefreshError(
            "diagnostic_dir and result_dir must be pathlib.Path objects"
        )
    destination = _prepare_new_result_destination(result_dir)
    expected_manifest_sha256 = _frozen_manifest_sha256()
    confirmations = {
        "map_prior_unchanged": confirm_map_prior_unchanged,
        "J2_powered_supervised": confirm_j2_powered_supervised,
        "cold_start": confirm_cold_start,
        "single_post_authorized": confirm_single_post_authorized,
    }
    if any(type(value) is not bool or value is not True for value in confirmations.values()):
        raise LowSpatialDiagnosticRefreshError(
            "all four explicit diagnostic confirmations are required"
        )
    if not isinstance(base_url, str) or not base_url.strip():
        raise LowSpatialDiagnosticRefreshError(
            "base_url must be a non-empty device root URL"
        )

    # This dedicated validator is the last operation before the permanent
    # authorization claim.  Neither the old candidate validator nor a generic
    # frame tool can substitute for it.
    snapshot = _load_diagnostic_snapshot(
        diagnostic_dir, expected_manifest_sha256
    )
    attempt_id = uuid.uuid4().hex
    created_at_utc = _utc_now()
    claim = _claim_authorization(
        snapshot,
        attempt_id=attempt_id,
        claimed_at_utc=created_at_utc,
        result_destination=destination,
    )

    directory: Optional[Path] = None
    try:
        directory = _create_result_directory(destination, snapshot, claim)
        lock = {
            "schema_version": SCHEMA_VERSION,
            "kind": LOCK_KIND,
            "attempt_id": attempt_id,
            "created_at_utc": created_at_utc,
            "state": "authorization_permanently_consumed_do_not_rerun",
            "diagnostic_manifest_file_sha256": snapshot.manifest_file_sha256,
            "diagnostic_frame_sha256": EXPECTED_FRAME_SHA256,
            "diagnostic_frame_fnv1a": f"0x{EXPECTED_FRAME_FNV1A:08X}",
            "declared_prior_frame": dict(EXPECTED_MAP_PRIOR),
            "fixed_controller_mappings": [
                _mapping_record(mapping) for mapping in FIXED_CONTROLLER_MAPPINGS
            ],
            "controllers": _controller_records(),
            "firmware": {
                "build_tag": EXPECTED_BUILD_TAG,
                "driver_api": EXPECTED_DRIVER_API,
                "panel": f"{WIDTH}x{HEIGHT}",
                "frame_bytes": FRAME_BYTES,
                "refresh_spi_hz": EXPECTED_REFRESH_SPI_HZ,
            },
            "authorization_claim": claim.reference(),
            "exact_action": dict(EXACT_ACTION),
            "confirmations": confirmations,
            "authorization_consumed_permanently": True,
            "automatic_retry_authorized": False,
            "automatic_recovery_authorized": False,
            "formal": False,
            "hardware_qualified": False,
            "hardware_tested": False,
            "algorithm_qualification": False,
        }
        _atomic_new_file(directory, LOCK_FILENAME, _canonical_json(lock))

        network_report = _perform_refresh_once(
            base_url,
            snapshot.frame,
            job_timeout_s=job_timeout_s,
            poll_interval_s=poll_interval_s,
            sleeper=sleeper,
            clock=clock,
        )
        result = {
            **_base_result(
                attempt_id=attempt_id,
                snapshot=snapshot,
                claim=claim,
                recorded_at_utc=_utc_now(),
            ),
            "outcome": "protocol_verified_manual_observation_required",
            "protocol_verified": True,
            "network_report": dict(network_report),
        }
        _atomic_new_file(directory, RESULT_FILENAME, _canonical_json(result))
        return result
    except BaseException as error:
        record_error: Optional[BaseException] = None
        try:
            if directory is not None:
                unknown = {
                    **_base_result(
                        attempt_id=attempt_id,
                        snapshot=snapshot,
                        claim=claim,
                        recorded_at_utc=_utc_now(),
                    ),
                    "outcome": "unknown_do_not_retry",
                    "protocol_verified": None,
                    "network_report": None,
                    "error": {"type": type(error).__name__, "message": str(error)},
                }
                _atomic_new_file(directory, RESULT_FILENAME, _canonical_json(unknown))
        except BaseException as result_error:
            record_error = result_error
        detail = (
            f"; diagnostic result could not be recorded ({record_error})"
            if record_error is not None
            else ""
        )
        raise LowSpatialDiagnosticRefreshUnknown(
            "low-spatial diagnostic outcome is unknown_do_not_retry; "
            f"the global claim is permanent{detail}"
        ) from error


def parse_args(argv: Optional[Sequence[str]] = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    parser.add_argument("--diagnostic-dir", type=Path, required=True)
    parser.add_argument("--result-dir", type=Path, required=True)
    parser.add_argument(
        "--url", required=True, help="device root URL on the trusted test network"
    )
    parser.add_argument("--confirm-map-prior-unchanged", action="store_true")
    parser.add_argument("--confirm-j2-powered-supervised", action="store_true")
    parser.add_argument("--confirm-cold-start", action="store_true")
    parser.add_argument("--confirm-single-post-authorized", action="store_true")
    return parser.parse_args(argv)


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = parse_args(argv)
    try:
        result = run_low_spatial_diagnostic_refresh_once(
            args.diagnostic_dir,
            args.result_dir,
            args.url,
            confirm_map_prior_unchanged=args.confirm_map_prior_unchanged,
            confirm_j2_powered_supervised=args.confirm_j2_powered_supervised,
            confirm_cold_start=args.confirm_cold_start,
            confirm_single_post_authorized=args.confirm_single_post_authorized,
        )
    except LowSpatialDiagnosticRefreshUnknown as error:
        print(f"UNKNOWN_DO_NOT_RETRY: {error}", file=sys.stderr)
        return 3
    except LowSpatialDiagnosticRefreshError as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 2
    print(_canonical_json(result).decode("utf-8"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
