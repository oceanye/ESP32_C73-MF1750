#!/usr/bin/env python3
"""Generate the WF A1/B1 bundle include: two L535 single-axis variants.

A1 (pll_only): active table + active PWR, only R20 header byte 6 (PLL code)
0x02 -> 0x03 and the runtime 0x30 payload byte follow.  Asserts
R20[6] == PLL[0] and PWR byte-identical to the sealed active PWR.

B1 (vsh_lv2_only): VSH_LV2 6200 -> 6900 mV.  R20 header byte 3 and PWR
payload byte 4 change as a pair (PWR = {0x0F} + header[0:5], evidence
spd1657_legacy_535_reference.inc active/commented payload symmetry).
Asserts R20[1:5] == PWR[2:6], PLL stays 0x02, R21 stays 704 x 0xFF.

Output: src/generated/spd1657_wf_ab_bundles.inc (O_EXCL content check).
No device, network, relay or camera access.
"""
from pathlib import Path
import hashlib
import json
import sys

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from host.runtime_waveform import l535_table_builder as builder  # noqa: E402

OUT = ROOT / "src/generated/spd1657_wf_ab_bundles.inc"
REPORT = ROOT / ".test-output/offline/WF_AB_BUNDLES_20261011_V1/generation-report.json"

VARIANTS = {
    "a1_pll50": {"pll_code": 0x03},
    "b1_vshlv2_6900": {"vsh_lv2_mv": 6900},
}


def _fmt_array(name: str, payload: bytes) -> str:
    lines = [f"static constexpr std::uint8_t {name}[{len(payload)}] = {{"]
    for i in range(0, len(payload), 16):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in payload[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main() -> None:
    reference = builder.from_reference("active")
    ref_bytes = reference.to_bytes()
    ref_header = bytes(reference.header)
    ref_pwr = bytes([0x0F]) + ref_header[0:5]

    out = [
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "// Generated by tools/mf1750_wf_ab_bundle_build.py from the sealed L535 active",
        "// reference table via host/runtime_waveform/l535_table_builder.py.",
        "// a1_pll50 changes ONLY header byte 6 (PLL code) plus the runtime 0x30 byte;",
        "// b1_vshlv2_6900 changes ONLY header byte 3 (VSH_LV2 code) plus the PWR",
        "// mirror byte 4.  Record bytes are inherited verbatim from active.",
        "",
        "namespace mf1750::runtime_lut::wf_ab {",
        "",
    ]
    report = {"reference_r20_sha256": hashlib.sha256(ref_bytes).hexdigest(),
              "reference_pwr_sha256": hashlib.sha256(ref_pwr).hexdigest(),
              "variants": {}}
    for name, knobs in VARIANTS.items():
        table = builder.build_table(knobs, records_from=reference)
        payload = table.to_bytes()
        header = bytes(table.header)
        if payload[7:] != ref_bytes[7:]:
            raise SystemExit(f"{name}: record region drifted")
        changed = [i for i in range(7) if payload[i] != ref_bytes[i]]
        expected_offset = 6 if name == "a1_pll50" else 3
        if changed != [expected_offset]:
            raise SystemExit(f"{name}: header drift at {changed}, expected [{expected_offset}]")
        if name == "a1_pll50":
            pwr = ref_pwr
            pll = bytes([header[6]])
            assert payload[6] == pll[0], "A1: R20[6] != PLL[0]"
        else:
            pwr = bytes([0x0F]) + header[0:5]
            pll = bytes([0x02])
            assert payload[1:5] == pwr[2:6], "B1: R20[1:5] != PWR[2:6]"
            assert payload[6] == 0x02, "B1: PLL drifted"
        entry = {
            "knobs": knobs,
            "r20_sha256": hashlib.sha256(payload).hexdigest(),
            "pwr_sha256": hashlib.sha256(pwr).hexdigest(),
            "pll_payload_sha256": hashlib.sha256(pll).hexdigest(),
            "pll_payload": list(pll),
            "pwr_payload": list(pwr),
            "header": list(header),
        }
        report["variants"][name] = entry
        out.append(f"namespace {name} {{")
        out.append(f"// knobs={knobs}; sha256(R20)={entry['r20_sha256']}")
        out.append(f"// sha256(PWR)={entry['pwr_sha256']}; sha256(PLL)={entry['pll_payload_sha256']}")
        out.append("static constexpr std::uint8_t kPowerPayload[6] = {")
        out.append("    " + ", ".join(f"0x{b:02X}" for b in pwr) + ",\n};")
        out.append("static constexpr std::uint8_t kPllPayload[1] = {")
        out.append(f"    0x{pll[0]:02X},\n}};")
        out.append(_fmt_array("kR20Payload", payload))
        out.append("}")
        out.append("")
    out.append("}  // namespace mf1750::runtime_lut::wf_ab")
    out.append("")
    content = "\n".join(out)
    if OUT.exists() and OUT.read_text(encoding="utf-8") != content:
        raise SystemExit("wf_ab include exists with different content - investigate first")
    OUT.write_text(content, encoding="utf-8")
    report["include_sha256"] = hashlib.sha256(content.encode()).hexdigest()
    REPORT.write_text(json.dumps(report, indent=1, sort_keys=True), encoding="utf-8")
    print(json.dumps({k: v["r20_sha256"][:16] for k, v in report["variants"].items()}, indent=1))
    print("written", OUT, "sha256", report["include_sha256"][:16])


if __name__ == "__main__":
    main()
