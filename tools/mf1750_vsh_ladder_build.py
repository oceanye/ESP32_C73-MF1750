#!/usr/bin/env python3
"""Generate the vsh_lv ladder include: three L535 tables differing only in vsh_lv.

Uses host.runtime_waveform.l535_table_builder (the sealed active reference plus
named header knobs).  For each rung (6000/6600/7200 mV) emits a namespace with
the 535-byte R20 table (knobbed header byte 1) and the matching PWR payload
(byte 2 carries the same code: PWR = {0x0F} + header[0:5], evidence
spd1657_legacy_535_reference.inc active/commented payload symmetry).

Output: src/generated/spd1657_l535_vsh_ladder.inc (O_EXCL content check).
No device, network, relay or camera access.
"""
from pathlib import Path
import hashlib
import sys

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from host.runtime_waveform import l535_table_builder as builder  # noqa: E402

OUT = ROOT / "src/generated/spd1657_l535_vsh_ladder.inc"
RUNGS = (6000, 6600, 7200)


def _fmt_array(name: str, payload: bytes) -> str:
    lines = [f"static constexpr std::uint8_t {name}[{len(payload)}] = {{"]
    for i in range(0, len(payload), 16):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in payload[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main() -> None:
    reference = builder.from_reference("active")
    out = [
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "// Generated by tools/mf1750_vsh_ladder_build.py from the sealed L535 active",
        "// reference table via host/runtime_waveform/l535_table_builder.py.  Each rung",
        "// changes ONLY the vsh_lv knob (R20 header byte 1 and PWR payload byte 2,",
        "// which mirrors header bytes 0..4); record bytes are inherited verbatim.",
        "",
        "namespace mf1750::runtime_lut::vsh_ladder {",
        "",
    ]
    shas = {}
    for rung in RUNGS:
        table = builder.build_table({"vsh_lv_mv": rung}, records_from=reference)
        payload = table.to_bytes()
        if payload[7:] != reference.to_bytes()[7:]:
            raise SystemExit(f"rung {rung}: record region drifted")
        if payload[0] != 0 or payload[2:] != reference.to_bytes()[2:]:
            raise SystemExit(f"rung {rung}: unexpected header drift")
        header = table.header
        pwr = bytes([0x0F]) + header[0:5]
        shas[rung] = hashlib.sha256(payload).hexdigest()
        ns = f"vsh{rung}"
        out.append(f"namespace {ns} {{")
        out.append(f"// vsh_lv = {rung} mV (code 0x{header[1]:02X}); sha256(R20) = {shas[rung]}")
        out.append(f"static constexpr std::uint8_t kPowerPayload[6] = {{")
        out.append("    " + ", ".join(f"0x{b:02X}" for b in pwr) + ",\n};")
        out.append(_fmt_array("kR20Payload", payload))
        out.append("}")
        out.append("")
    out.append("}  // namespace mf1750::runtime_lut::vsh_ladder")
    out.append("")
    content = "\n".join(out)
    if OUT.exists() and OUT.read_text(encoding="utf-8") != content:
        raise SystemExit("ladder include exists with different content - investigate first")
    OUT.write_text(content, encoding="utf-8")
    print("rungs:", {r: s[:16] for r, s in shas.items()})
    print("written", OUT, "sha256", hashlib.sha256(content.encode()).hexdigest()[:16])


if __name__ == "__main__":
    main()
